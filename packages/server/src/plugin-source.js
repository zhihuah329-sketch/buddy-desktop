/**
 * The plugin source this app ships, generated at install time.
 *
 * ## Why it is generated and not shipped as a fixed file
 *
 * The plugin declares which harness packages it runs against. Those versions differ
 * between users — a user on an older or newer harness than this app was built with
 * would get a package whose `peerDependencies` cannot be satisfied, and the harness
 * would skip it. The versions are therefore read from the harness that is actually
 * present, and the manifest is written to match it.
 *
 * The adapter source itself is plain text with a single substitution: the `/v1` base
 * the plugin forwards to, which depends on the port this app ends up listening on.
 *
 * @module @buddy-desktop/server/plugin-source
 */

/**
 * The adapter source.
 *
 * Kept as a template so the port can be injected. Everything else is literal.
 */
export const ADAPTER_SOURCE = `/**
 * Command Buddy Connect — the provider plugin Buddy Desktop installs.
 *
 * Generated by Buddy Desktop. Holds no credentials: every request is forwarded to
 * the desktop app, which owns the account pools, the rotation and the quota.
 *
 * @module dsh-command-buddy-connect-standalone
 */

import { LlmAdapter, LlmError } from '@deepseek-ai/dsh-llm'

/** The provider id. Appears in saved model ids, so it is a wire contract. */
export const PROVIDER_ID = 'command-buddy-connect'

/** What the model picker shows. */
export const PROVIDER_NAME = 'Command Buddy Connect'

/** Where the desktop app serves. */
const BASE = '__BASE__'

/** The models this provider offers. */
const MODELS = ['deepseek-v4.1-flash-cn', 'deepseek-v4.1-flash-ai']

/** How deep a conversation this provider accepts. */
const CONTEXT_WINDOW = 128000

/** The reasoning levels offered. */
const REASONING_EFFORTS = ['low', 'medium', 'high']

/**
 * The adapter the harness talks to.
 *
 * The method set is fixed by \`LlmAdapter\`: list what exists, describe one model,
 * prepare a call, then stream it. Each answers a Promise.
 */
export class DesktopAdapter extends LlmAdapter {
  constructor(options = {}) {
    super()
    this.base = typeof options.base === 'string' && options.base.length > 0
      ? options.base.replace(/\\/+$/, '')
      : BASE
    this.logger = options.logger
    /** Takes the region, because one adapter serves both pools. */
    this.isEnabled = options.isEnabled ?? (() => true)
  }

  /** @inheritdoc */
  listModels(provider) {
    return Promise.resolve(MODELS.map((id) => ({
      provider,
      id,
      name: id,
      inputModalities: ['text']
    })))
  }

  /** @inheritdoc */
  resolveModel(provider, model) {
    if (!MODELS.includes(model)) {
      return Promise.reject(new LlmError(
        PROVIDER_NAME + ' 没有模型「' + model + '」，它提供 ' + MODELS.join(' 和 ') + '。',
        'UNKNOWN_MODEL'
      ))
    }
    return Promise.resolve({
      provider,
      id: model,
      name: model,
      inputModalities: ['text'],
      context: { contextWindow: CONTEXT_WINDOW },
      reasoning: { efforts: REASONING_EFFORTS }
    })
  }

  /** @inheritdoc */
  async prepareCall(provider, model, signal) {
    return {
      model: await this.resolveModel(provider, model, signal),
      stream: (options) => this.stream(options)
    }
  }

  /** @inheritdoc */
  async *stream(options) {
    const model = options.model
    const site = model.endsWith('-ai') ? 'ai' : 'cn'

    if (this.isEnabled(site) !== true) {
      throw new LlmError(
        (site === 'cn' ? '国内版' : '国际版') + '线路已在桌面应用里停用，启用后才能调用。',
        'PROVIDER_DISABLED'
      )
    }

    const payload = {
      model,
      messages: toWireMessages(options.messages),
      stream: true
    }
    if (typeof options.temperature === 'number') payload.temperature = options.temperature
    if (typeof options.maxTokens === 'number') payload.max_tokens = options.maxTokens

    let response
    try {
      response = await fetch(this.base + '/chat/completions', {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          'x-buddy-desktop-client': 'plugin'
        },
        body: JSON.stringify(payload),
        signal: options.signal
      })
    } catch (error) {
      throw new LlmError(
        '连不上桌面应用（' + this.base + '）。请确认 Buddy Desktop 正在运行。',
        'PROVIDER_UNREACHABLE',
        { cause: error }
      )
    }

    if (!response.ok) {
      throw new LlmError(await failureMessage(response), 'PROVIDER_FAILED')
    }

    for await (const frame of readSse(response.body)) {
      if (frame === null) continue
      const delta = frame.choices?.[0]?.delta
      if (delta === undefined) continue
      if (typeof delta.reasoning_content === 'string' && delta.reasoning_content.length > 0) {
        yield { type: 'reasoning', text: delta.reasoning_content }
      }
      if (typeof delta.content === 'string' && delta.content.length > 0) {
        yield { type: 'text', text: delta.content }
      }
    }
  }
}

/** The reason out of a failed response. */
async function failureMessage(response) {
  try {
    const body = await response.json()
    if (typeof body?.error?.message === 'string') return body.error.message
  } catch {
    // A body that does not parse leaves the status text.
  }
  return '桌面应用返回 ' + response.status
}

/** Harness messages, reduced to the text the upstream accepts. */
function toWireMessages(messages) {
  const out = []
  for (const message of messages ?? []) {
    const role = message.role === 'assistant'
      ? 'assistant'
      : message.role === 'system'
        ? 'system'
        : 'user'
    let text = ''
    for (const block of message.content ?? []) {
      if (block?.type === 'text' && typeof block.text === 'string') text += block.text
    }
    if (text.length > 0) out.push({ role, content: text })
  }
  return out
}

/** Parse an SSE body frame by frame. */
async function* readSse(body) {
  if (body === null || body === undefined) return
  const decoder = new TextDecoder()
  let buffer = ''
  for await (const chunk of body) {
    buffer += decoder.decode(chunk, { stream: true })
    let boundary = buffer.indexOf('\\n\\n')
    while (boundary !== -1) {
      const raw = buffer.slice(0, boundary)
      buffer = buffer.slice(boundary + 2)
      for (const line of raw.split('\\n')) {
        if (!line.startsWith('data:')) continue
        const data = line.slice(5).trim()
        if (data.length === 0 || data === '[DONE]') {
          yield null
          continue
        }
        try {
          yield JSON.parse(data)
        } catch {
          yield null
        }
      }
      boundary = buffer.indexOf('\\n\\n')
    }
  }
}

/** The plugin, as the harness loads it. */
export default {
  name: 'dsh-command-buddy-connect-standalone',
  apply(ctx, config = {}) {
    const adapter = new DesktopAdapter({
      base: config.base,
      logger: ctx.logger,
      isEnabled: () => config.enableProvider !== false
    })
    ctx.effect(
      () => ctx.llm.registerAdapter([PROVIDER_ID], adapter),
      'dsh-command-buddy-connect-standalone: adapter registration'
    )
    ctx.logger?.info?.('registered provider "' + PROVIDER_ID + '" (' + PROVIDER_NAME + ')')
  }
}
`

/**
 * The manifest, built around whatever harness version is present.
 *
 * @param options - `llmVersion` (the harness's own package version, if known).
 * @returns the manifest object.
 */
export function buildManifest(options = {}) {
  const manifest = {
    name: 'dsh-command-buddy-connect-standalone',
    displayName: 'Command Buddy Connect',
    description: 'Buddy Desktop model routes: CN and AI pools served by the desktop app.',
    version: '2.0.0',
    type: 'module',
    private: false,
    main: 'index.js',
    exports: {
      '.': './index.js',
      './package.json': './package.json'
    },
    files: ['index.js'],
    license: 'MIT',
    keywords: ['dsh-plugin', 'deepseek-harness', 'model-provider']
  }

  // The peer range is filled from the harness when it can be read. A version that
  // does not match what is installed would make the harness skip the package, so an
  // unknown version gets no constraint at all rather than a wrong one.
  if (typeof options.llmVersion === 'string' && options.llmVersion.length > 0) {
    manifest.peerDependencies = { '@deepseek-ai/dsh-llm': `^${options.llmVersion}` }
  }

  return manifest
}
